"""Build the small icon font the app ships instead of all of Bootstrap Icons.

The full font is ~135 KB and its stylesheet describes ~2,000 icons inside the
render-blocking CSS; the app uses a few dozen. This writes a font holding only the
icons named in web/src (as `bi-<name>`) and the CSS for just those.

Run from the repository root after using a new icon (tests/test_web_icons.py fails
until you do):

    uvx --with fonttools --with brotli python web/scripts/subset-icons.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "node_modules" / "bootstrap-icons" / "font"
OUT = ROOT / "src" / "icons"
NAME = re.compile(r"\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)")


def used_icons() -> list[str]:
    names: set[str] = set()
    for path in (ROOT / "src").rglob("*"):
        if path.suffix in {".html", ".ts", ".scss"} and OUT not in path.parents:
            names.update(NAME.findall(path.read_text()))
    return sorted(names)


def main() -> int:
    codepoints: dict[str, int] = json.loads((PACKAGE / "bootstrap-icons.json").read_text())
    icons = used_icons()
    unknown = [name for name in icons if name not in codepoints]
    if unknown:
        print("Not in Bootstrap Icons:", ", ".join(unknown), file=sys.stderr)
        return 1
    OUT.mkdir(exist_ok=True)
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []
    options.name_IDs = []
    options.notdef_outline = False
    font = subset.load_font(str(PACKAGE / "fonts" / "bootstrap-icons.woff"), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[codepoints[name] for name in icons])
    subsetter.subset(font)
    subset.save_font(font, str(OUT / "bootstrap-icons-subset.woff2"), options)
    rules = "\n".join(
        f'.bi-{name}::before {{ content: "\\{codepoints[name]:x}"; }}' for name in icons
    )
    (OUT / "bootstrap-icons-subset.css").write_text(
        f"""/*!
 * Bootstrap Icons v1.13.2 (https://icons.getbootstrap.com/), the {len(icons)} icons Fareflare uses.
 * Copyright 2019-2024 The Bootstrap Authors. Licensed under MIT
 * (https://github.com/twbs/icons/blob/main/LICENSE).
 * Generated by web/scripts/subset-icons.py; do not edit.
 */

@font-face {{
  font-display: block;
  font-family: "bootstrap-icons";
  src: url("./bootstrap-icons-subset.woff2") format("woff2");
}}

.bi::before,
[class^="bi-"]::before,
[class*=" bi-"]::before {{
  display: inline-block;
  font-family: bootstrap-icons !important;
  font-style: normal;
  font-weight: normal !important;
  font-variant: normal;
  text-transform: none;
  line-height: 1;
  vertical-align: -.125em;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}}

{rules}
"""
    )
    size = (OUT / "bootstrap-icons-subset.woff2").stat().st_size
    print(f"{len(icons)} icons, {size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
